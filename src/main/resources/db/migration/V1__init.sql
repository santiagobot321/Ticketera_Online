CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255),
    capacity INT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255) NOT NULL,
    date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    venue_id BIGINT,
    PRIMARY KEY (id)
);
